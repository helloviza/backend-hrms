/* ── THE FIXTURE ──────────────────────────────────────────────────────
 * A structurally valid TD3 machine-readable zone for a fictional Indian
 * passport. Every check digit is correct, so the deterministic parser
 * accepts it and deriveConfidence returns "high" — which is what lets the
 * provenance assertions below distinguish VERIFIED from MACHINE_READ
 * rather than everything collapsing into a failure.
 *
 * Written out as LITERALS rather than computed by calling this repo's own
 * computeCheckDigit at test time: a fixture generated by the code under
 * test proves only that the code agrees with itself. These digits were
 * computed once, out-of-band, from the ICAO 9303 7-3-1 rule.
 *
 * The values are chosen to exercise both converters at once:
 *   - "IND"    -> normaliseToIso2 -> "IN"     (ISO3→ISO2)
 *   - "900411" -> resolveMrzDate("dob")    -> "1990-04-11"
 *                 The dob rule specifically: 2090 would be in the future,
 *                 so it falls back a century. A naive 2000+YY gives 2090.
 *   - "300815" -> resolveMrzDate("expiry") -> "2030-08-15"
 *                 The expiry rule: ALWAYS this century, no comparison.
 *                 The two rules disagreeing is the whole point of testing
 *                 both — 30 resolves forward here and 90 resolves back.
 */
const MRZ_LINE1_CONTENT = "P<INDSHARMA<<PRIYA<ANITA";
const MRZ_LINE2 = "Z1234567<1IND9004115F3008155<<<<<<<<<<<<<<08";

function geminiReply(overrides: Record<string, any> = {}) {
  return {
    text: JSON.stringify({
      mrz_found: true,
      line1_content: MRZ_LINE1_CONTENT,
      line2: MRZ_LINE2,
      viz_found: false,
      viz: null,
      ...overrides,
    }),
  };
}

async function makeConsumer(email: string) {
  const consumer = await Consumer.create({
    email,
    name: email.split("@")[0],
    passwordHash: "not-used-in-these-tests",
  });
  createdConsumerIds.push(String(consumer._id));
  const token = signConsumerAccessToken({
    consumerId: String(consumer._id),
    tokenVersion: (consumer as any).tokenVersion,
  });
  return { id: String(consumer._id), token };
}

/**
 * A real document row with real bytes behind it, written through the SAME
 * driver the route reads back through. Not a row pointing at nothing: the
 * local-disk path is exactly the incompatibility this feature exists to
 * handle (getObjectBuffer, the B2B path, cannot read it), so a test that
 * skipped the write would skip the one genuinely new line of plumbing.
 */
async function makePassportDoc(consumerId: string, docCode = "PASSPORT_ORIGINAL") {
  const stored = await putConsumerDocument({
    buffer: Buffer.from("not-a-real-jpeg-the-model-is-mocked"),
    mime: "image/jpeg",
    originalName: "passport.jpg",
    consumerId,
  });
  return ConsumerDocument.create({
    consumerId: new mongoose.Types.ObjectId(consumerId),
    workspaceId: new mongoose.Types.ObjectId(),
    category: "IDENTITY",
    docCode,
    driver: stored.driver,
    storageKey: stored.storageKey,
    bucket: stored.bucket,
    originalFilename: "passport.jpg",
    mimeType: "image/jpeg",
    sizeBytes: 35,
  });
}

const auth = (token: string) => ["Authorization", `Bearer ${token}`] as const;

