// apps/backend/src/routes/consumer.passportExtract.test.ts
//
// ══════════════════════════════════════════════════════════════════════
// POST /api/consumer/profile/documents/:id/extract
//
// FOUR CLAIMS, AND THE FIRST TWO ARE THE NON-NEGOTIABLE ONES:
//   1. OWN-SCOPED  — consumer B cannot read consumer A's passport.
//   2. NO PERSIST  — the route writes NOTHING. Not a field, not a status.
//   3. MAPPED      — the ten Applicant fields come back with an honest
//                    provenance tier per field, converted by the SAME
//                    ISO3→ISO2 / century logic the B2B path uses.
//   4. NO 500s     — an unreadable passport is a 422 with a category the
//                    UI can turn into a sentence, never a server error.
// ══════════════════════════════════════════════════════════════════════
//
// WHAT IS REAL HERE, AND WHAT IS NOT.
//
// Real: the router, requireConsumer, consumer tokens, Mongo
// (mongodb-memory-server), the ConsumerDocument rows, the local-disk
// storage driver (services/consumerDocumentStorage.ts — NODE_ENV is
// "test", so activeDriver() returns "local-disk" and the bytes genuinely
// go to and come back from .devdata/), services/consumerPassportExtraction
// .ts, services/extractPassportGemini.ts, utils/mrz.ts, utils/countryCodes
// .ts and utils/passportCrossCheck.ts.
//
// Mocked: @google/genai, and only that. It is the network boundary, not
// the thing under test — the same line services/extractPassportGemini
// .test.ts already draws. Everything between the HTTP request and that
// boundary runs for real, which is the point: this proves the engine is
// actually reusable from the consumer path, rather than proving that a
// stub returns what the stub was told to return.
